/** Spoken card name, e.g. "Cinco de Espadas" / "Five of Spades". */
export function cardSpoken(c: Card): string {
  return lang() === 'pt' ? `${RANK_PT[rankOf(c)]} de ${SUIT_PT[suitOf(c)]}` : `${RANK_EN[rankOf(c)]} of ${SUIT_EN[suitOf(c)]}`;
}

/** Short label with the suit as a symbol, e.g. "5♠" or "D♥". */
export function cardShort(c: Card): string {
  const r = lang() === 'pt' ? RANK_SHORT_PT[rankOf(c)] : RANK_CODES[rankOf(c)];
  return r + SUIT_SYMBOLS[suitOf(c)];
}

export function kindName(kind: string): string {
  return t((['pair', 'trio', 'quad', 'straight'].includes(kind) ? kind : 'formation') as Key);
}
